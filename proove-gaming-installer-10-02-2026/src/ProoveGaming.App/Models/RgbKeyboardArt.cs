using System;
using System.Collections.Generic;
using System.Threading.Tasks;
using Avalonia.Media;
using Avalonia.Platform;
using Avalonia.Svg.Skia;

namespace ProoveGaming.App.Models;

/// <summary>
/// The three pieces needed to render a keyboard with a live backlight: the chassis layer,
/// the keycap layer drawn over it, and the geometry of the backlight itself. The artwork
/// ships as a single SVG per keyboard, but the glow is only visible in the gaps between
/// keycaps, so it has to be drawn *between* those two layers — hence the split.
/// </summary>
/// <param name="BaseSvg">Chassis layer, resource path.</param>
/// <param name="KeysSvg">Keycaps + legends, transparent background, drawn last.</param>
/// <param name="GlowPathAsset">Path-data asset for the key-well shape the backlight fills.</param>
/// <param name="CardSvg">
/// The vendor artwork as delivered, before the backlight was stripped for the layered
/// rendering. Used on the home card, which wants the product shot rather than a board whose
/// lighting follows the picker.
/// </param>
/// <param name="Width">Artwork viewBox width — the glow and legend geometry are in these units.</param>
/// <param name="Height">Artwork viewBox height.</param>
/// <param name="LegendPathAsset">
/// Keycap legend outlines, path-data asset. Null for a board whose artwork does not separate them
/// (T800), in which case the legends stay part of the keycap image and simply do not follow the
/// backlight — the view renders no legend layer rather than failing.
/// </param>
/// <param name="UnlitLegendColor">
/// What the legends are drawn in when the board is shown unlit — by default the colour they were
/// fixed at in the artwork before extraction. Keeps the click-target rendering on Key Assignments
/// and Macros looking exactly as it did, and readable, which a backlight-tinted legend would not be
/// at low brightness. Legibility wins where the two conflict: a board whose keycaps are close to
/// the artwork colour overrides it (Rampage — see the catalog).
/// </param>
public sealed record RgbKeyboardArt(
	string BaseSvg,
	string KeysSvg,
	string GlowPathAsset,
	string CardSvg,
	double Width,
	double Height,
	string? LegendPathAsset = null,
	string UnlitLegendColor = "#0f53ff")
{
	/// <summary>Card artwork as an avares URI, for SvgImageView (which caches its raster).</summary>
	public string CardSvgUri => $"avares://ProoveGaming.App{CardSvg}";

	private Geometry? _glow;

	/// <summary>
	/// Backlight shape, parsed from <see cref="GlowPathAsset"/> on first use and cached.
	/// Aress alone is ~12 KB of path data, which is why this lives in an asset rather than
	/// a source literal. Returns null if the asset is missing or unparseable, which the
	/// view treats as "no glow" rather than failing to render the keyboard.
	/// </summary>
	public Geometry? Glow
	{
		get
		{
			if (_glow is not null) return _glow;
			try
			{
				using var stream = AssetLoader.Open(new Uri($"avares://ProoveGaming.App{GlowPathAsset}"));
				using var reader = new System.IO.StreamReader(stream);
				_glow = Geometry.Parse(reader.ReadToEnd().Trim());
			}
			catch
			{
				_glow = null;
			}
			return _glow;
		}
	}

	private Geometry? _legends;
	private bool _legendsParsed;

	/// <summary>
	/// Keycap legend outlines, parsed once and cached. Null when the board has no legend asset, or
	/// when the asset is missing or unparseable — the view then draws no legend layer, the same way
	/// it treats a missing glow.
	/// </summary>
	/// <remarks>
	/// These are the glyphs lifted out of the artwork's <c>#text-solid</c> group, which took its fill
	/// from a CSS variable pinned to one brand colour. Owning the geometry is what lets the legends
	/// follow the backlight: re-parsing an ~800 KB SVG to change that variable would have to happen
	/// on every animation frame. Generated by
	/// <c>docs/plans/tint-keyboard-legends/extract-legends.py</c>.
	/// </remarks>
	public Geometry? Legends
	{
		get
		{
			// Cached through the failure cases too — a missing asset must not re-open on every
			// render pass, and Legends is read once per layer per rebuild.
			if (_legendsParsed) return _legends;
			_legendsParsed = true;

			if (string.IsNullOrEmpty(LegendPathAsset)) return _legends = null;

			try
			{
				using var stream = AssetLoader.Open(new Uri($"avares://ProoveGaming.App{LegendPathAsset}"));
				using var reader = new System.IO.StreamReader(stream);
				_legends = Geometry.Parse(reader.ReadToEnd().Trim());
			}
			catch
			{
				_legends = null;
			}
			return _legends;
		}
	}

	public bool HasLegends => Legends is not null;

	// ── Preloaded SVG layers ──────────────────────────────────────────────────
	// The BLAZE treatment for keyboards (see DeviceDetailsViewModel.PrewarmDeviceOnlyBitmapAsync):
	// parsing the ~800 KB chassis/keycap SVGs takes long enough to visibly lag the instant-painting
	// Path layers, so HomeViewModel prewarms them as soon as a keyboard's card is known and the
	// view picks up synchronously-ready sources instead of decoding on open. Cached here because
	// each catalog record is a process-wide singleton.
	private SvgSource? _baseSource;
	private SvgSource? _keysSource;
	private Task? _sourcesLoad;

	/// <summary>Preloaded chassis layer; null until <see cref="EnsureSourcesAsync"/> completes.</summary>
	public SvgSource? BaseSource => _baseSource;

	/// <summary>Preloaded keycap layer; null until <see cref="EnsureSourcesAsync"/> completes.</summary>
	public SvgSource? KeysSource => _keysSource;

	/// <summary>
	/// Loads both SVG layers once, parsing off the calling thread; subsequent calls return the
	/// same task. Callers are UI-thread only (HomeViewModel's prewarm, RgbKeyboardView's apply),
	/// which is what makes the unsynchronised coalescing safe.
	/// </summary>
	public Task EnsureSourcesAsync() => _sourcesLoad ??= LoadSourcesAsync();

	private async Task LoadSourcesAsync()
	{
		_baseSource = await LoadSvgSourceAsync(BaseSvg);
		_keysSource = await LoadSvgSourceAsync(KeysSvg);
	}

	// The asset stream is drained on the calling (UI) thread — avares assets are in-memory
	// resources, so the copy is cheap — and the expensive parse runs in Task.Run. Null on any
	// failure: the view then renders no chassis/keycap layer, the same way it treats a missing
	// glow asset.
	private static async Task<SvgSource?> LoadSvgSourceAsync(string assetPath)
	{
		try
		{
			byte[] bytes;
			using (var stream = AssetLoader.Open(new Uri($"avares://ProoveGaming.App{assetPath}")))
			using (var buffer = new System.IO.MemoryStream())
			{
				stream.CopyTo(buffer);
				bytes = buffer.ToArray();
			}

			return await System.Threading.Tasks.Task.Run(
				() => SvgSource.LoadFromStream(new System.IO.MemoryStream(bytes)));
		}
		catch
		{
			return null;
		}
	}

	private IBrush? _unlitLegendBrush;

	/// <summary>Fill for the unlit legend layer; white if the configured colour will not parse.</summary>
	public IBrush UnlitLegendBrush =>
		_unlitLegendBrush ??= Color.TryParse(UnlitLegendColor, out var c)
			? new SolidColorBrush(c)
			: Brushes.White;
}

/// <summary>
/// Which keyboards have split artwork and can therefore show a live RGB preview. Keyed by
/// the catalog device name (<c>DeviceName</c> in the DeviceHost allow-list). A keyboard absent
/// from this map falls back to the flat single-layer image with no live backlight.
/// </summary>
public static class RgbKeyboardArtCatalog
{
	private const string Dir = "/Assets/Keyboards";

	private static readonly Dictionary<string, RgbKeyboardArt> Map =
		new(StringComparer.OrdinalIgnoreCase)
		{
			// LegendPathAsset + UnlitLegendColor: the glyphs extracted from each artwork's #text-solid
			// group, and the colour they were fixed at there. T800 passes neither — its artwork has no
			// such group, so its legends stay in the keycap image and do not follow the backlight.
			//
			// T-Racer's CardSvg points at the delivered artwork rather than a Card/ entry: the vendor
			// shipped one render, so a Card/ copy would be a byte-for-byte duplicate. If a lit product
			// shot arrives later, add Card/PG_T-Racer_card.svg and repoint this one field.
			["Raster"] = new($"{Dir}/PG_Raster_base.svg",  $"{Dir}/PG_Raster_keys.svg",  $"{Dir}/Glow/Raster.path",  $"{Dir}/Card/PG_Raster_card.svg",  1529.288, 701.593, $"{Dir}/Legend/Raster.path",  "#0f53ff"),
			// Rampage is the one board that does NOT keep its artwork's legend colour (PG-688). Its
			// keycaps are blue-violet, so the artwork's #0f53ff legends sit at a contrast ratio of
			// 1.05-1.41 against them — 1.0 being indistinguishable — and whole rows read as blank
			// caps on Key Assignments and Macros. The cap colour alone is the cause: the board's
			// KeyOverlayArtDim scrim (0.15) darkens legend and cap together and barely moves the
			// ratio. #00FF3C is the RGB picker's own bright green (RgbColorPickerControl's preset
			// swatch, so no new colour enters the palette) and lifts the same samples to 2.97-5.30,
			// best exactly where it was worst: the dark bottom-row modifiers.
			["Rampage"] = new($"{Dir}/PG_Rampage_base.svg", $"{Dir}/PG_Rampage_keys.svg", $"{Dir}/Glow/Rampage.path", $"{Dir}/Card/PG_Rampage_card.svg", 1471.412, 577.563, $"{Dir}/Legend/Rampage.path", "#00FF3C"),
			// Aress's artwork was delivered on a 1571.695 x 1563.529 near-square canvas with the
			// board in a band across the middle — uncropped, the Viewbox scales to the empty
			// square and the board renders about a third of the size Cyrex gets, on the home card
			// and the details RGB view alike. Same treatment as T800 below: base/keys viewBoxes
			// are cropped to the band ("30.2 536.8 1510.5 487.3", the chassis alpha bounds plus
			// ~5px), these are the crop's dimensions, and Glow/Legend paths are shifted by the
			// crop origin.
			["Aress"] = new($"{Dir}/PG_Aress_base.svg",   $"{Dir}/PG_Aress_keys.svg",   $"{Dir}/Glow/Aress.path",   $"{Dir}/Card/PG_Aress_card.svg",   1510.5, 487.3, $"{Dir}/Legend/Aress.path",   "#e63c3c"),
			["Cyrex"] = new($"{Dir}/PG_Cyrex_base.svg",   $"{Dir}/PG_Cyrex_keys.svg",   $"{Dir}/Glow/Cyrex.path",   $"{Dir}/Card/PG_Cyrex_card.svg",   1472.469, 480.666, $"{Dir}/Legend/Cyrex.path",   "#e63c3c"),
			// T800's artwork was delivered as a 1920-square canvas with the board in a band across
			// the middle, two thirds of it empty. All four assets are cropped to that band
			// (viewBox "172 672 1742 600"), so these are the crop's dimensions rather than the
			// delivered file's, and Glow/T800.path is shifted by the same origin. Left uncropped,
			// the Viewbox scales to the empty square and the board renders about a third of the
			// size every other keyboard gets — on the home card and the details page alike.
			["T800"] = new($"{Dir}/PG_T801_base.svg",    $"{Dir}/PG_T801_keys.svg",    $"{Dir}/Glow/T800.path",    $"{Dir}/Card/PG_T801_card.svg",    1742, 600),
			["T-Racer"] = new($"{Dir}/PG_T-Racer_base.svg", $"{Dir}/PG_T-Racer_keys.svg", $"{Dir}/Glow/T-Racer.path", $"{Dir}/PG_Keyboard_RGB-off_T-Racer_black.svg", 1595.294, 689.31, $"{Dir}/Legend/T-Racer.path", "#0f53ff"),
		};

	public static RgbKeyboardArt? For(string? deviceName) =>
		!string.IsNullOrWhiteSpace(deviceName) && Map.TryGetValue(deviceName, out var art) ? art : null;

	/// <summary>
	/// Preloads the named board's SVG layers (no-op for devices without split artwork). Called
	/// from HomeViewModel as soon as a keyboard's card is known — the keyboard analogue of the
	/// mouse glow-bitmap prewarm, and for the same reason: by the time the user can click into
	/// Details, the art is already parsed.
	/// </summary>
	public static Task PrewarmAsync(string? deviceName) =>
		For(deviceName)?.EnsureSourcesAsync() ?? Task.CompletedTask;
}
